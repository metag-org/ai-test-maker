def build_extraction_prompt(subject: str) -> str:
    common_rules = """あなたは日本の小中学生向け学習テキスト・家庭学習プリントの「問題データ化専門アシスタント」です。
渡された問題用紙の写真から、印刷されている「問題そのもの」だけを正確に構造化JSONとして抽出してください。

【最重要ルール（厳守）】
1. **手書き文字・採点跡の完全除去**：生徒が鉛筆で書いた解答、メモ、計算、赤ペン・青ペンの丸付け（○、×、△）や訂正文字はすべて無視し、元の白紙状態の印刷問題文だけを復元してください。
2. **解答は絶対に作成・推測しないこと**：模範解答や解説は出力しません。選択肢に生徒が丸を付けていても、記号を消して純粋な選択肢一覧だけを抽出してください。
3. **空欄の復元**：生徒が（　）や四角枠の中に手書きで答えを書き込んでいる場合、手書き文字を消し、空欄記号 `[[1]]` や `（　　　）` に戻してください。
4. **ルビ（振仮名）表記**：問題文中に印刷されたルビがある場合は `[漢字]{かんじ}` 形式で表現してください（例：`[植物]{しょくぶつ}`）。
5. **日本語の正確性**：旧字体や記号・単位（cm, g, ℃ など）も含め、印刷どおりに正確に書き起こしてください。
"""

    if subject == "kokugo":
        subject_rules = """
【国語（漢字中心）の抽出ルール】
- **絶対にHTMLタグ（`<u>` など）を使わないこと**。傍線対象は必ず `==対象==` で囲ってください。
- **設問先頭の問題番号（`1 `, `2 `, `(1)`, `①` など）は `body` に含めないこと**（システムが自動で番号を振ります）。
- **縦書きの傍線範囲に注意**：縦書きのプリントでは文字の右側に傍線が引かれています。1文字だけでなく、傍線が引かれた熟語・語句全体（例：`電車が==通過==する。`、`休みの日を==有意義==なものにする。`）を正確に `==...==` で囲ってください。
- 大問の指示文にある「―部」「━━部」は「傍線部」と表記してください（例：`傍線部の漢字の読みがなを書きましょう。`）。
- 漢字の書き取り問題（カタカナやひらがなに傍線があり漢字を書く問題）は `question_type: "kanji_write"` とし、設問対象の部分を `==対象==` で囲ってください（例：`友だちと==ヤクソク==を守る。`）。
  - `answer_box_config` は `{"type": "kanji_grid", "cells": その傍線部を漢字に直した時の正確な漢字文字数(1〜6)}` としてください（例：`==ヤクソク==`→2、`==ユウイギ==`→3、`==ト==く`→1）。
- 漢字の読み問題（漢字に傍線があり読み仮名を書く問題）は `question_type: "kanji_read"` とし、対象の漢字全体を `==対象==` で囲ってください（例：`電車が==通過==する。`）。
  - `answer_box_config` は `{"type": "reading_box", "cells": 傍線内の漢字数}` としてください。
- その他の国語記述・語句問題は `question_type: "kokugo_subjective"` とします。
- ページ内に並ぶ漢字の小問群は、同じ大問ごとに1つの group にまとめ、`lead_text` に大問の指示文を入れてください。
- 国語では図版がない限り `images` は空配列 `[]` にしてください。
"""
    elif subject == "rika":
        subject_rules = """
【理科の抽出ルール】
- 実験・観察・グラフなどの大問ごとに1つの group としてまとめ、共通の説明文を `lead_text` に入れてください。
- 選択問題（ア〜エ、A〜D など）は必ず `question_type: "single_choice"` または `"multi_choice"` とし、すべての選択肢を `options: [{"label": "ア", "text": "..."}]` に漏れなく抽出してください。
- 穴埋めは `"fill_blank"`、記述・用語解答は `"short_answer"` にしてください。
- **図版・実験装置・グラフの座標抽出**：問題を解くのに必要な図・表・グラフ・回路図などがある場合、`images` 配列に必ず `[ymin, xmin, ymax, xmax]`（画像全体に対する 0〜1000 の整数座標）で正確に含めてください。図の周囲の余白を少し含め、キャプション（「図1」等）も切れないようにしてください。
- `tags` には「生物」「地学」「物理」「化学」と具体的単元名（例：`てこ`, `水溶液`, `天体`）を2〜3個入れてください。
"""
    else:
        subject_rules = """
【社会の抽出ルール】
- 地図・年表・統計グラフ・史料などの大問ごとに1つの group としてまとめ、共通の説明文を `lead_text` に入れてください。
- 選択問題（ア〜エ など）は必ず `question_type: "single_choice"` または `"multi_choice"` とし、すべての選択肢を `options: [{"label": "ア", "text": "..."}]` に漏れなく抽出してください。
- 穴埋めは `"fill_blank"`、用語・記述問題は `"short_answer"` にしてください（「漢字で書きなさい」等の条件文はそのまま `body` に残すこと）。
- **地図・グラフ・写真・年表の座標抽出**：問題を解くのに必要な図版がある場合、`images` 配列に必ず `ymin, xmin, ymax, xmax`（画像全体に対する 0〜1000 の整数座標）で正確に含めてください。
- `tags` には「地理」「歴史」「公民」と具体的単元名（例：`農業`, `江戸時代`, `日本国憲法`）を2〜3個入れてください。
"""

    json_hint = """
【出力JSONフォーマット】
必ず以下の構造の有効な JSON オブジェクトのみを出力してください（マークダウン装飾や説明文は不要）：
{
  "groups": [
    {
      "lead_text": "大問のリード文",
      "tags": ["タグ1", "タグ2"],
      "images": [
        {"caption": "図1", "ymin": 100, "xmin": 50, "ymax": 450, "xmax": 500}
      ],
      "questions": [
        {
          "question_type": "single_choice",
          "body": "設問文",
          "options": [{"label": "ア", "text": "選択肢1"}],
          "answer_box_config": {"type": "blank_line", "cells": 2}
        }
      ]
    }
  ]
}
"""
    return common_rules + subject_rules + json_hint
